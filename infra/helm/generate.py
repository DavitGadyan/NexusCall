def vault_policies() -> dict[str, list[dict[str, Any]]]:
    """Parse every `write_policy <name> <path stanza>...` call in infra/vault/bootstrap.sh."""
    text = (ROOT / "infra" / "vault" / "bootstrap.sh").read_text()
    body = re.search(r"write_policy\(\) \{(.*?)\n\}", text, re.S)
    if body is None:
        fail("write_policy() not found in bootstrap.sh")
    for expected in (
        'echo "path \\"secret/data/${E}/platform/${name}/*\\" { capabilities = [\\"read\\"] }"',
        """echo 'path "auth/token/renew-self" { capabilities = ["update"] }'""",
        """echo 'path "auth/token/lookup-self" { capabilities = ["read"] }'""",
    ):
        if expected not in body.group(1):  # type: ignore[union-attr]
            fail(f"write_policy() template changed; update generate.py (missing: {expected})")
    joined = re.sub(r"\\\n\s*", " ", text)
    macros = {"${T}": "secret/data/{env}/tenants/+", "${M}": "secret/metadata/{env}/tenants/+", "${E}": "{env}"}
    stanza = re.compile(r'^path "([^"]+)" \{ capabilities = \[([^\]]*)\] \}$')
    policies: dict[str, list[dict[str, Any]]] = {}
    for raw_line in joined.splitlines():
        line = raw_line.strip()
        if not line.startswith("write_policy ") or line.startswith("write_policy()"):
            continue
        name, *args = shlex.split(line)[1:]
        rules = [{"path": "secret/data/{env}/platform/" + name + "/*", "capabilities": ["read"]}]
        for raw_arg in args:
            arg = raw_arg
            for k, v in macros.items():
                arg = arg.replace(k, v)
            m = stanza.match(arg)
            if m is None:
                fail(f"cannot parse policy stanza for {name}: {arg}")
            caps = [c.strip().strip('"') for c in m.group(2).split(",")]  # type: ignore[union-attr]
            rules.append({"path": m.group(1), "capabilities": caps})  # type: ignore[union-attr]
        rules += [
            {"path": "auth/token/renew-self", "capabilities": ["update"]},
            {"path": "auth/token/lookup-self", "capabilities": ["read"]},
        ]
        policies[name] = rules
    expected_names = {s[0] for s in gen_compose.SERVICES} | {"web-bff"}
    if set(policies) != expected_names:
        fail(f"bootstrap.sh policies do not match the services: {sorted(set(policies) ^ expected_names)}")
    return policies


def broker_roles() -> dict[str, Any]:
    digest = hashlib.sha256(inspect.getsource(bootstrap_rabbitmq.main).encode()).hexdigest()
    if digest != BROKER_MAIN_SHA256:
        fail(
            "scripts/bootstrap_rabbitmq.py main() changed: re-check broker_roles() against it, then set "
            f"BROKER_MAIN_SHA256 = {digest!r}"
        )
    roles: dict[str, Any] = {}
    for svc, prefixes in bootstrap_rabbitmq.PUBLISH.items():
        q = bootstrap_rabbitmq.TASK_QUEUES.get(svc)
        own = f"events\\.{svc.replace('-', '_')}.*"
        task_q = f"|{q}\\..*|celery.*|celeryev.*|.*\\.pidbox" if q else ""
        write_keys = "|".join(["audit\\.event", *[f"{p}(\\..*)?" for p in prefixes]])
        roles[svc] = {
            "configure": f"^({own}{task_q}|nexus\\.(events|tasks|dlx))$",
            "write": f"^({own}{task_q}|nexus\\.(events|tasks|dlx)|amq\\.default)$",
            "read": f"^({own}{task_q}|nexus\\.(events|tasks|dlx))$",
            "topic_exchange": "nexus.events",
            "topic_write": f"^({write_keys})$",
            "topic_read": ".*",
        }
    return roles


def task_queues() -> list[str]:
    """nexus_core QUEUES plus any queue a generated worker consumes (each gets a <queue>.dlq)."""
    extra = [q for w in gen_compose.WORKERS for q in queues_from_command(list(w[2])) if q not in QUEUES]
    return [*QUEUES, *dict.fromkeys(extra)]


def dlq_policy_pattern() -> str:
    return str(bootstrap_rabbitmq.TASK_DLQ_POLICY_PATTERN)


def topology() -> dict[str, Any]:
    queues = task_queues()
    pattern = dlq_policy_pattern()
    return {
        "_comment": "GENERATED by infra/helm/generate.py; do not edit by hand.",
        "databases": {s[0]: s[2] for s in gen_compose.SERVICES},
        "task_exchange": {"name": "nexus.tasks", "type": "topic"},
        "event_exchange": {"name": "nexus.events", "type": "topic"},
        "dead_letter_exchange": {"name": DLX_EXCHANGE, "type": "topic"},
        "task_queues": queues,
        "dead_letter_queues": [f"{q}.dlq" for q in queues],
        # Mirrors the development policy exactly. Queues it does not match still dead-letter through the
        # x-dead-letter-exchange argument that nexus_core.celery_app.create_celery sets on every queue.
        "dlq_policy": {
            "name": "task-dlq",
            "pattern": pattern,
            "definition": {"dead-letter-exchange": DLX_EXCHANGE, "delivery-limit": 6},
            "unmatched_queues": [q for q in queues if not re.match(pattern, q)],
        },
        "broker_roles": broker_roles(),
        "vault_policies": vault_policies(),
    }


def generated_block() -> str:
    services, workers, notes = components()
    data = {
        "services": services,
        "workers": workers,
        "routes": routes(),
        "generatedNotes": {
            "requiredEnv": notes["required"],
            "forbiddenEnv": FORBIDDEN_ENV,
            "queuesWithoutWorker": notes["queuesWithoutWorker"],
            "externalEgressReasons": EXTERNAL_EGRESS,
        },
    }
    return yaml.safe_dump(data, sort_keys=False, width=120)


def render_values(current: str) -> str:
    if BEGIN not in current or END not in current:
        fail(f"{VALUES} is missing the GENERATED markers")
    head, rest = current.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{BEGIN}\n{generated_block()}{END}{tail}"


def main(argv: list[str]) -> int:
    check = "--check" in argv
    new_values = render_values(VALUES.read_text())
    new_topology = json.dumps(topology(), indent=2, sort_keys=False) + "\n"
    stale = []
    if VALUES.read_text() != new_values:
        stale.append(str(VALUES.relative_to(ROOT)))
    if not TOPOLOGY.exists() or TOPOLOGY.read_text() != new_topology:
        stale.append(str(TOPOLOGY.relative_to(ROOT)))
    if check:
        if stale:
            print("stale generated deployment config: " + ", ".join(stale), file=sys.stderr)
            print("run: uv run python infra/helm/generate.py", file=sys.stderr)
            return 1
        print("deployment config is up to date")
        return 0
    VALUES.write_text(new_values)
    TOPOLOGY.parent.mkdir(parents=True, exist_ok=True)
    TOPOLOGY.write_text(new_topology)
    print("wrote " + ", ".join([str(VALUES.relative_to(ROOT)), str(TOPOLOGY.relative_to(ROOT))]))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
