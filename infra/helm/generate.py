#!/usr/bin/env python3
"""Generate the deployment topology for Kubernetes from the development sources of truth.

Sources (read-only; owned by the platform team):
  scripts/gen_compose.py       SERVICES and WORKERS: which services and workers exist, their extra env
  scripts/gen_traefik.py       render(): every edge router (prefixes, unbuffered SSE/WebSocket, upload limits)
  infra/vault/bootstrap.sh     write_policy calls: the per-service Vault policy paths
  scripts/bootstrap_rabbitmq.py PUBLISH / TASK_QUEUES: per-service broker permissions
  nexus_core.celery_app        QUEUES: task queues, each with a <queue>.dlq on nexus.dlx

Outputs:
  infra/helm/nexuscall/values.yaml     the block between the GENERATED markers (services, workers, routes)
  infra/terraform/generated/topology.json   Vault policies, broker roles and queues for Terraform

Usage:
  uv run python infra/helm/generate.py           # rewrite the outputs
  uv run python infra/helm/generate.py --check   # exit 1 if an output is stale (CI)

Anything the generator cannot classify (a new compose env key, an unknown Traefik middleware, a new
service-to-service call found in the code) is an error: a human must decide how it maps to production.
"""

