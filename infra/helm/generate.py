def fail(msg: str) -> None:
    print(f"generate.py: {msg}", file=sys.stderr)
    raise SystemExit(2)


def queues_from_command(command: list[str]) -> list[str]:
    if "-Q" not in command:
        fail(f"worker command has no -Q: {command}")
    return command[command.index("-Q") + 1].split(",")


def env_for(service: str, extra: dict[str, str]) -> tuple[dict[str, str], dict[str, dict[str, str]], list[str]]:
    env: dict[str, str] = {}
    secret_env: dict[str, dict[str, str]] = {}
    required: list[str] = []
    for key, dev_value in extra.items():
        if key not in PROD_ENV:
            fail(f"{service}: compose env {key!r} has no production mapping in PROD_ENV")
        mode, arg = PROD_ENV[key]
        if mode == "keep":
            env[key] = dev_value
        elif mode == "value":
            env[key] = arg
        elif mode == "required":
            env[key] = ""
            required.append(key)
        elif mode == "secret":
            path, field = arg
            secret_env[key] = {"path": path.format(service=service), "field": field}
    return env, secret_env, required


def routes() -> list[dict[str, Any]]:
    """Every router from gen_traefik.render(), mapped to chart routes. Webhook prefixes get their own
    route (no user traffic, separate middleware chain) so provider callbacks are isolated from the API."""
    rendered = yaml.safe_load(gen_traefik.render())["http"]
    out: list[dict[str, Any]] = []
    for name, r in rendered["routers"].items():
        unknown = set(r["middlewares"]) - MIDDLEWARES.keys()
        if unknown:
            fail(f"router {name}: unknown middleware(s) {sorted(unknown)}")
        eps = [ENTRYPOINTS[e] for e in r["entryPoints"]]
        middlewares = [MIDDLEWARES[m] for m in r["middlewares"]]
        terms = [t.strip() for t in r["rule"].split("||")]
        hooks = [t for t in terms if re.match(r"^PathPrefix\(`/webhooks/", t)]
        rest = [t for t in terms if t not in hooks]
        kind = "standard"
        if "body-limit" not in r["middlewares"] and "body-limit-uploads" not in r["middlewares"]:
            kind = "websocket" if name == "voice-media" else "stream"
        elif "body-limit-uploads" in r["middlewares"]:
            kind = "upload"
        if rest:
            out.append(
                {
                    "name": name,
                    "service": r["service"],
                    "match": " || ".join(rest),
                    "priority": r["priority"],
                    "entryPoints": eps,
                    "middlewares": middlewares,
                    "kind": kind,
                }
            )
        if hooks:
            out.append(
                {
                    "name": f"{name}-webhooks",
                    "service": r["service"],
                    "match": " || ".join(hooks),
                    "priority": r["priority"] + 50,
                    "entryPoints": ["public"],
                    "middlewares": ["secure-headers", "rate-limit-webhooks", "body-limit-webhooks"],
                    "kind": "webhook",
                }
            )
    return out


def code_edges() -> set[tuple[str, str]]:
    """Service-to-service calls found in the service code (service_client / runtime.client / adapters)."""
    pkg_to_name = {s[1]: s[0] for s in gen_compose.SERVICES}
    pattern = re.compile(
        r"""(?:service_client\([^,()]+,\s*|\.client\(|InternalAdapter\("[^"]+",\s*)"([a-z-]+)\"""", re.VERBOSE
    )
    edges: set[tuple[str, str]] = set()
    for pkg, name in pkg_to_name.items():
        src = ROOT / "services" / pkg / pkg
        if not src.is_dir():
            continue
        for file in src.rglob("*.py"):
            for target in pattern.findall(file.read_text()):
                if target in DEPENDS and target != name:
                    edges.add((name, target))
    return edges


def components() -> tuple[dict[str, Any], list[dict[str, Any]], dict[str, list[str]]]:
    names = [s[0] for s in gen_compose.SERVICES]
    if sorted(names) != sorted(DEPENDS):
        fail(f"DEPENDS does not match gen_compose.SERVICES: {sorted(set(names) ^ set(DEPENDS))}")
    missing = {(a, b) for a, b in code_edges() if b not in DEPENDS[a]}
    if missing:
        fail(f"service calls found in code but missing from DEPENDS: {sorted(missing)}")
    route_services = {r["service"] for r in routes()}
    services: dict[str, Any] = {}
    required: dict[str, list[str]] = {}
    for name, pkg, db, profiles, extra in gen_compose.SERVICES:
        env, secret_env, req = env_for(name, extra)
        if req:
            required[name] = req
        size = {**SIZING["default"], **SIZING.get(name, {})}
        services[name] = {
            "enabled": True,
            "image": name,
            "package": pkg,
            "database": db,
            "profiles": profiles,
            "port": 8000,
            "replicas": size["replicas"],
            "resources": {
                "requests": {"cpu": size["cpu"], "memory": size["memory"]},
                "limits": {"cpu": size["cpuLimit"], "memory": size["memoryLimit"]},
            },
            "hpa": {
                "enabled": True,
                "minReplicas": size["replicas"],
                "maxReplicas": size["replicas"] * 4,
                "targetCPUUtilizationPercentage": 70,
            },
            "terminationGracePeriodSeconds": GRACE_SECONDS.get(name, 30),
            "public": name in route_services,
            "dependsOn": sorted(DEPENDS[name]),
            "infra": BASE_INFRA + EXTRA_INFRA.get(name, []),
            "externalEgress": name in EXTERNAL_EGRESS,
            "env": env,
            "secretEnv": secret_env,
        }
    by_name = {s[0]: s for s in gen_compose.SERVICES}
    workers: list[dict[str, Any]] = []
    for wname, owner, command, profiles in gen_compose.WORKERS:
        if owner not in by_name:
            fail(f"worker {wname}: unknown owner {owner}")
        _, pkg, db, _, extra = by_name[owner]
        env, secret_env, _ = env_for(owner, extra)
        workers.append(
            {
                "name": wname,
                "owner": owner,
                "command": list(command),
                "queues": queues_from_command(list(command)),
                "profiles": profiles,
                "replicas": 2,
                "resources": {
                    "requests": {"cpu": "100m", "memory": "256Mi"},
                    "limits": {"cpu": "1", "memory": "512Mi"},
                },
                "terminationGracePeriodSeconds": WORKER_GRACE_OVERRIDES.get(wname, WORKER_GRACE_SECONDS),
                "env": env,
                "secretEnv": secret_env,
            }
        )
    unowned = set(QUEUES) - {q for w in workers for q in w["queues"]}
    return services, workers, {"required": required, "queuesWithoutWorker": sorted(unowned)}  # type: ignore[dict-item]


