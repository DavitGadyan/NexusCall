def sync_catalogue() -> None:
    """Seed/refresh the code-defined permission catalogue and system roles (idempotent).

    Catalogue changes ship as a new migration that calls this function again."""
    from sqlalchemy.dialects.postgresql import insert

    from tenant_service.catalogue import PLATFORM_PERMISSIONS, SYSTEM_ROLES, TENANT_PERMISSIONS
    from tenant_service.tables import permissions, roles

    for key, desc in {**TENANT_PERMISSIONS, **PLATFORM_PERMISSIONS}.items():
        scope = "platform" if key.startswith("platform:") else "tenant"
        op.execute(
            insert(permissions)
            .values(key=key, scope=scope, description=desc)
            .on_conflict_do_update(index_elements=["key"], set_={"description": desc})
        )
    for role in SYSTEM_ROLES:
        op.execute(
            insert(roles)
            .values(
                key=role.key,
                name=role.name,
                scope=role.scope,
                description=role.description,
                is_system=True,
                requires_mfa=role.requires_mfa,
            )
            .on_conflict_do_update(
                index_elements=["key"],
                set_={"name": role.name, "description": role.description, "requires_mfa": role.requires_mfa},
            )
        )
        # Role keys and permission keys come from the code catalogue (validated identifiers), never user input.
        op.execute(f"DELETE FROM role_permissions WHERE role_id = (SELECT id FROM roles WHERE key = '{role.key}')")
        for p in sorted(role.permissions):
            op.execute(
                "INSERT INTO role_permissions (role_id, permission_key) "
                f"SELECT id, '{p}' FROM roles WHERE key = '{role.key}'"
            )


