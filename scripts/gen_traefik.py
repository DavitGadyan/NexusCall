# No Traefik `buffering` middleware: it also buffers responses, which turns empty responses (303 without
# a body, 204) into 500 and breaks streaming. Body size limits are enforced by every service
# (nexus_core BodySizeLimitMiddleware: 1 MiB default, 11 MiB for upload services) and by the web BFF.
MIDDLEWARES = "[secure-headers, rate-limit]"


def render() -> str:
    out = [
        "# GENERATED by scripts/gen_traefik.py; do not edit by hand.",
        "http:",
        "  routers:",
        "    web:",
        '      rule: "PathPrefix(`/`)"',
        "      priority: 1",
        "      service: web",
        f"      middlewares: {MIDDLEWARES}",
        "      entryPoints: [web]",
    ]
    for svc, prefixes in ROUTES.items():
        rule = " || ".join(f"PathPrefix(`{p}`)" for p in prefixes)
        out += [
            f"    {svc}:",
            f'      rule: "{rule}"',
            "      priority: 100",
            f"      service: {svc}",
            f"      middlewares: {MIDDLEWARES}",
            "      entryPoints: [web, internal]",
        ]
    # Twilio Media Streams is a WebSocket: no buffering middleware.
    out += [
        "    voice-media:",
        '      rule: "PathPrefix(`/media/twilio`)"',
        "      priority: 300",
        "      service: voice-service",
        "      middlewares: [secure-headers, rate-limit]",
        "      entryPoints: [web]",
    ]
    # Server-sent events must not pass the buffering middleware (it buffers response bodies too).
    out += [
        "    notification-stream:",
        '      rule: "Path(`/api/v1/notifications/stream`)"',
        "      priority: 300",
        "      service: notification-service",
        "      middlewares: [secure-headers, rate-limit]",
        "      entryPoints: [web, internal]",
    ]
    out += ["  services:", "    web:", "      loadBalancer:", '        servers: [{ url: "http://web:3000" }]']
    for svc in ROUTES:
        out += [f"    {svc}:", "      loadBalancer:", f'        servers: [{{ url: "http://{svc}:8000" }}]']
    out += [
        "  middlewares:",
        "    secure-headers:",
        "      headers:",
        "        frameDeny: true",
        "        contentTypeNosniff: true",
        "        referrerPolicy: strict-origin-when-cross-origin",
        '        permissionsPolicy: "camera=(), geolocation=(), microphone=()"',
        '        customResponseHeaders: { X-Powered-By: "", Server: "" }',
        "    rate-limit:",
        "      rateLimit: { average: 100, burst: 200, period: 1s }",
    ]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    (ROOT / "infra" / "traefik" / "dynamic.yml").write_text(render())
    print("wrote infra/traefik/dynamic.yml")
